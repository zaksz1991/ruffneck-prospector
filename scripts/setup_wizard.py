#!/usr/bin/env python3
"""
RuffNeck Prospector – Simple Setup Wizard (100% free stack)
Run: python scripts/setup_wizard.py
"""
import os
import sys
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = ROOT / ".env"
ENV_EXAMPLE = ROOT / ".env.example"

def ask(prompt, default=""):
    if default:
        val = input(f"{prompt} [{default}]: ").strip()
        return val or default
    return input(f"{prompt}: ").strip()

def yes_no(prompt, default=True):
    d = "Y/n" if default else "y/N"
    val = input(f"{prompt} ({d}): ").strip().lower()
    if not val:
        return default
    return val in ("y", "yes")

def main():
    print("\n" + "="*60)
    print("  RuffNeck Prospector – Free Setup Wizard")
    print("="*60 + "\n")

    print("This wizard helps you create a working .env file and checks basic requirements.\n")

    if ENV_FILE.exists():
        if not yes_no(".env already exists. Overwrite it?", default=False):
            print("Keeping existing .env. Exiting.")
            return

    print("→ Required free accounts:")
    print("  1. Supabase (https://supabase.com) – free project")
    print("  2. Groq (https://console.groq.com) – free API key\n")

    supabase_url = ask("Supabase Project URL")
    supabase_key = ask("Supabase service_role key")
    groq_key = ask("Groq API Key")

    redis_url = ask("Redis URL", "redis://localhost:6379/0")
    location = ask("Default location for daily discovery (optional)", "")

    # Optional
    print("\n→ Optional free keys (press Enter to skip):")
    reddit_id = ask("Reddit Client ID", "")
    reddit_secret = ask("Reddit Client Secret", "")
    youtube_key = ask("YouTube Data API Key", "")
    smtp_user = ask("Gmail address for free sending", "")
    smtp_pass = ask("Gmail App Password", "")

    content = f"""# Generated by setup_wizard.py
SUPABASE_URL={supabase_url}
SUPABASE_KEY={supabase_key}
GROQ_API_KEY={groq_key}
GROQ_MODEL=llama-3.3-70b-versatile
REDIS_URL={redis_url}

REDDIT_CLIENT_ID={reddit_id}
REDDIT_CLIENT_SECRET={reddit_secret}
REDDIT_USER_AGENT=RuffNeckProspector/1.4

YOUTUBE_API_KEY={youtube_key}

SMTP_HOST=smtp.gmail.com
SMTP_PORT=587
SMTP_USER={smtp_user}
SMTP_PASS={smtp_pass}
FROM_NAME=RuffNeck Services
FROM_EMAIL={smtp_user}
"""
    ENV_FILE.write_text(content)
    print(f"\n✅ Wrote {ENV_FILE}")

    # Quick checks
    print("\n→ Checking Python packages...")
    try:
        import fastapi, celery, supabase, groq
        print("  Core packages look present.")
    except ImportError as e:
        print(f"  Missing package: {e}")
        print("  Run: cd backend && pip install -r requirements.txt")

    print("\n→ Playwright (needed for Maps / LinkedIn / Facebook)")
    if yes_no("Install Playwright chromium now?", default=True):
        try:
            subprocess.check_call([sys.executable, "-m", "playwright", "install", "chromium"])
            print("  Playwright chromium installed.")
        except Exception as e:
            print(f"  Could not install automatically: {e}")
            print("  Run manually: playwright install chromium")

    print("\n" + "="*60)
    print("  Next steps")
    print("="*60)
    print("""
1. In Supabase → SQL Editor → paste & run database/schema.sql
2. Start Redis (local or Docker)
3. Terminal 1:  cd backend && uvicorn app.main:app --reload --port 8000
4. Terminal 2:  cd backend && celery -A app.tasks.celery_app worker --loglevel=info
5. Frontend:    cd frontend && npm install && npm run dev
6. Open http://localhost:3000/discover  → click “Run Daily Discovery”
""")
    if location:
        print(f"Tip: Your default location is set to “{location}”. You can change it on the Daily tab.")
    print("Happy prospecting! (100% free)\n")

if __name__ == "__main__":
    main()
